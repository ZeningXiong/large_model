"""Generate src/unicode_data.h: code point ranges for Unicode categories L* (letters) and N*
(numbers), as used by the Qwen2 pre-tokenizer regex (\\p{L}, \\p{N}).

    python -I tools/gen_unicode.py > src/unicode_data.h
"""
import sys
import unicodedata


def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


letters = ranges(lambda cp: cat(cp).startswith("L"))
numbers = ranges(lambda cp: cat(cp).startswith("N"))

w = sys.stdout.write
w("/* unicode_data.h - generated by tools/gen_unicode.py from Python's unicodedata "
  f"(Unicode {unicodedata.unidata_version}). Do not edit. */\n")
w("#ifndef QMS_UNICODE_DATA_H\n#define QMS_UNICODE_DATA_H\n\n#include <stdint.h>\n\n")
for name, rs in (("letter", letters), ("number", numbers)):
    w(f"static const uint32_t qms_uni_{name}[][2] = {{\n")
    for i in range(0, len(rs), 4):
        w("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 4]) + "\n")
    w("};\n")
    w(f"#define QMS_UNI_{name.upper()}_N {len(rs)}\n\n")
w("#endif /* QMS_UNICODE_DATA_H */\n")
